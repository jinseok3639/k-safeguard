"""난독화 생성기가 쓰는 표준발음법 음운 규칙 표.

표는 호환 자모 문자로 적어 표준발음법 조항과 눈으로 대조할 수 있게 하고, 모듈 끝에서 인덱스
기반 lookup으로 파생한다. 조항 번호는 국립국어원 표준발음법 기준이다. 변환 함수는
:mod:`k_safeguard.obfuscate`에 있다.
"""

from __future__ import annotations

from .normalization import COMPAT_CHO, COMPAT_JONG, COMPAT_JUNG

CHO_INDEX = {char: index for index, char in enumerate(COMPAT_CHO)}
JUNG_INDEX = {char: index for index, char in enumerate(COMPAT_JUNG)}
JONG_INDEX = {char: index for index, char in enumerate(COMPAT_JONG) if char}

# --------------------------------------------------------------------------
# 제12항 1 — 격음화(유기음화). ㅎ과 평음이 만나면 거센소리 하나로 축약된다.
# --------------------------------------------------------------------------

# 평음 -> 거센소리. 뒤 음절 초성이 ㅎ일 때 앞 종성이 이 표를 타고 올라간다.
LAX_TO_ASPIRATE = {"ㄱ": "ㅋ", "ㄷ": "ㅌ", "ㅂ": "ㅍ", "ㅈ": "ㅊ"}
ASPIRATE_TO_LAX = {v: k for k, v in LAX_TO_ASPIRATE.items()}

# (가) 앞 음절 종성 ㅎ 계열 + 뒤 음절 초성 평음 -> 거센소리. 놓고->노코, 좋다->조타.
#      겹받침은 ㅎ만 떨어지고 앞 자음이 종성에 남는다. 많지->만치, 닳지->달치.
H_CODA_RESIDUE = {"ㅎ": "", "ㄶ": "ㄴ", "ㅀ": "ㄹ"}
H_FOLLOWING_ONSET = {"ㄱ": "ㅋ", "ㄷ": "ㅌ", "ㅈ": "ㅊ", "ㅅ": "ㅆ"}  # ㅅ은 제12항 3 (닿소->다쏘)

# (나) 앞 음절 종성 평음 + 뒤 음절 초성 ㅎ -> 거센소리. 국화->구콰, 맏형->마텽, 좁히다->조피다.
#      겹받침은 뒤 자음만 ㅎ과 합쳐지고 앞 자음이 남는다. 앉히다->안치다, 밝히다->발키다.
#      값 = (종성에 남길 자모, 뒤 음절 초성이 될 거센소리)
CODA_PLUS_H = {
    "ㄱ": ("", "ㅋ"),
    "ㄺ": ("ㄹ", "ㅋ"),
    "ㄷ": ("", "ㅌ"),
    "ㅅ": ("", "ㅌ"),      # 평파열음화를 거쳐 ㄷ이 된 뒤 축약. 옷하고->오타고
    "ㅆ": ("", "ㅌ"),
    "ㅈ": ("", "ㅊ"),
    "ㄵ": ("ㄴ", "ㅊ"),
    "ㅂ": ("", "ㅍ"),
    "ㄼ": ("ㄹ", "ㅍ"),
}

# --------------------------------------------------------------------------
# 제12항 4 — ㅎ 탈락. 종성 ㅎ 뒤에 모음(초성 ㅇ)이 오면 ㅎ이 발음되지 않는다.
# 좋아->조아, 많아->마나, 싫어->시러, 낳은->나은.
# 겹받침이면 ㅎ만 떨어지고 남은 자음이 연음된다(ㄶ->ㄴ이 뒤로, ㅀ->ㄹ이 뒤로).
# --------------------------------------------------------------------------

# 값 = (종성에 남길 자모, 뒤 음절 초성으로 넘길 자모). 넘길 게 없으면 None(ㅇ 유지).
H_CODA_BEFORE_VOWEL = {
    "ㅎ": ("", None),
    "ㄶ": ("", "ㄴ"),
    "ㅀ": ("", "ㄹ"),
}

# --------------------------------------------------------------------------
# 제8·9항 — 음절의 끝소리 규칙(평파열음화). 종성은 7개로만 발음된다.
# 부엌->부억, 옷->옫, 빛->빋, 앞->압, 히읗->히읃.
# 다대일 사상이라 원리적으로 되돌릴 수 없는 부분이 생긴다(ㅅㅆㅈㅊㅌ이 전부 ㄷ).
# --------------------------------------------------------------------------

CODA_NEUTRALIZE = {
    "ㅋ": "ㄱ", "ㄲ": "ㄱ",
    "ㅅ": "ㄷ", "ㅆ": "ㄷ", "ㅈ": "ㄷ", "ㅊ": "ㄷ", "ㅌ": "ㄷ", "ㅎ": "ㄷ",
    "ㅍ": "ㅂ",
}

# --------------------------------------------------------------------------
# 제10·11항 — 자음군 단순화. 겹받침은 둘 중 하나만 발음된다.
# 값->갑, 넋->넉, 닭->닥, 삶->삼, 여덟->여덜, 읽다->익따.
# --------------------------------------------------------------------------

CLUSTER_REDUCE = {
    "ㄳ": "ㄱ", "ㄵ": "ㄴ", "ㄶ": "ㄴ", "ㄺ": "ㄱ", "ㄻ": "ㅁ",
    "ㄼ": "ㄹ", "ㄽ": "ㄹ", "ㄾ": "ㄹ", "ㄿ": "ㅂ", "ㅀ": "ㄹ", "ㅄ": "ㅂ",
}

# --------------------------------------------------------------------------
# 제18·19항 — 비음화.
# --------------------------------------------------------------------------

# (가) 파열음의 비음화: 종성 파열음 + 초성 ㄴ/ㅁ -> 종성이 같은 자리 비음으로.
#      국물->궁물, 닫는->단는, 밥물->밤물, 먹는->멍는.
CODA_TO_NASAL = {
    "ㄱ": "ㅇ", "ㄲ": "ㅇ", "ㅋ": "ㅇ", "ㄳ": "ㅇ", "ㄺ": "ㅇ",
    "ㄷ": "ㄴ", "ㅅ": "ㄴ", "ㅆ": "ㄴ", "ㅈ": "ㄴ", "ㅊ": "ㄴ", "ㅌ": "ㄴ", "ㅎ": "ㄴ",
    "ㅂ": "ㅁ", "ㅍ": "ㅁ", "ㄼ": "ㅁ", "ㄿ": "ㅁ", "ㅄ": "ㅁ",
}
NASAL_ONSETS = ("ㄴ", "ㅁ")

# (나) ㄹ의 비음화: 종성 ㅁ/ㅇ + 초성 ㄹ -> 초성이 ㄴ으로. 종로->종노, 강릉->강능, 담력->담녁.
NASAL_CODA_BEFORE_R = ("ㅁ", "ㅇ")

# (다) 상호 비음화: 종성 파열음 + 초성 ㄹ -> 종성은 비음으로, 초성은 ㄴ으로.
#      백리->뱅니, 섭리->섬니, 국력->궁녁.

# --------------------------------------------------------------------------
# 제20항 — 유음화. ㄴ과 ㄹ이 만나면 ㄹㄹ로 발음된다.
# 신라->실라, 난로->날로, 칼날->칼랄, 설날->설랄, 권력->궐력.
# --------------------------------------------------------------------------

# 방향이 둘이다: 종성 ㄴ + 초성 ㄹ -> 종성을 ㄹ로 / 종성 ㄹ + 초성 ㄴ -> 초성을 ㄹ로.

# --------------------------------------------------------------------------
# 제23~28항 — 경음화(된소리되기). 장애음 종성 뒤 평음은 경음으로 발음된다.
# 국밥->국빱, 학교->학꾜, 먹다->먹따, 옷고름->옫꼬름.
# 기존 `tensify`가 문맥과 무관하게 아무 평음 초성이나 경음으로 바꾸는 것과 대비된다.
# --------------------------------------------------------------------------

OBSTRUENT_CODAS = (
    "ㄱ", "ㄲ", "ㅋ", "ㄳ", "ㄺ",
    "ㄷ", "ㅅ", "ㅆ", "ㅈ", "ㅊ", "ㅌ",
    "ㅂ", "ㅍ", "ㄼ", "ㄿ", "ㅄ",
)
TENSIFIABLE_ONSETS = ("ㄱ", "ㄷ", "ㅂ", "ㅅ", "ㅈ")

# --------------------------------------------------------------------------
# 모음 혼동 — 표준발음법 조항이 아니라 **표기 혼동**이다.
#
# 현대 한국어 화자가 실제로 구분하지 못하거나 자주 틀리는 모음 짝.
# 규칙이 아니라 표기 혼동이므로 FAMILY는 'phonetic'이되 조항 근거는 없다.
# --------------------------------------------------------------------------

VOWEL_CONFUSION_GROUPS = (
    ("ㅐ", "ㅔ"),            # 가장 흔함. 재/제, 대/데
    ("ㅒ", "ㅖ"),
    ("ㅚ", "ㅙ", "ㅞ"),      # 되/돼/뒈
    ("ㅢ", "ㅣ", "ㅔ"),      # 의->이/에 (희망->히망, 의사->에사)
)


# --------------------------------------------------------------------------
# 인덱스 파생 — 위 표를 슬롯 인덱스 기반 lookup으로 바꾼다.
# --------------------------------------------------------------------------

def _jong(char: str) -> int:
    """종성 문자 -> 인덱스. 빈 문자열은 '받침 없음'(0)."""
    return JONG_INDEX[char] if char else 0


TENSIFIABLE_ONSET_INDICES = frozenset(CHO_INDEX[c] for c in TENSIFIABLE_ONSETS)
OBSTRUENT_CODA_INDICES = frozenset(JONG_INDEX[c] for c in OBSTRUENT_CODAS)
NASAL_ONSET_INDICES = frozenset(CHO_INDEX[c] for c in NASAL_ONSETS)
NASAL_CODA_BEFORE_R_INDICES = frozenset(JONG_INDEX[c] for c in NASAL_CODA_BEFORE_R)

# 격음화 (가): 종성 ㅎ계열 -> 남길 종성 / 뒤 초성 평음 -> 거센소리
H_CODA_RESIDUE_IDX = {JONG_INDEX[k]: _jong(v) for k, v in H_CODA_RESIDUE.items()}
H_FOLLOWING_ONSET_IDX = {CHO_INDEX[k]: CHO_INDEX[v] for k, v in H_FOLLOWING_ONSET.items()}

# 격음화 (나): 종성 평음 + 초성 ㅎ -> (남길 종성, 거센소리 초성)
CODA_PLUS_H_IDX = {
    JONG_INDEX[k]: (_jong(keep), CHO_INDEX[asp]) for k, (keep, asp) in CODA_PLUS_H.items()
}

# ㅎ 탈락: 종성 ㅎ계열 + 초성 ㅇ -> (남길 종성, 뒤로 넘길 초성 또는 None)
H_CODA_BEFORE_VOWEL_IDX = {
    JONG_INDEX[k]: (_jong(keep), CHO_INDEX[move] if move else None)
    for k, (keep, move) in H_CODA_BEFORE_VOWEL.items()
}

CODA_NEUTRALIZE_IDX = {JONG_INDEX[k]: JONG_INDEX[v] for k, v in CODA_NEUTRALIZE.items()}
CLUSTER_REDUCE_IDX = {JONG_INDEX[k]: JONG_INDEX[v] for k, v in CLUSTER_REDUCE.items()}
CODA_TO_NASAL_IDX = {JONG_INDEX[k]: JONG_INDEX[v] for k, v in CODA_TO_NASAL.items()}

LAX_TO_TENSE_ONSET_IDX = {
    CHO_INDEX[lax]: CHO_INDEX[tense]
    for lax, tense in {"ㄱ": "ㄲ", "ㄷ": "ㄸ", "ㅂ": "ㅃ", "ㅅ": "ㅆ", "ㅈ": "ㅉ"}.items()
}

# 유음화
JONG_N, JONG_R = JONG_INDEX["ㄴ"], JONG_INDEX["ㄹ"]
CHO_N, CHO_R = CHO_INDEX["ㄴ"], CHO_INDEX["ㄹ"]

# 모음 혼동: 중성 인덱스 -> 바꿔칠 수 있는 다른 중성 인덱스 목록
VOWEL_CONFUSION_IDX: dict[int, tuple[int, ...]] = {}
for _group in VOWEL_CONFUSION_GROUPS:
    for _member in _group:
        _others = tuple(JUNG_INDEX[o] for o in _group if o != _member)
        VOWEL_CONFUSION_IDX.setdefault(JUNG_INDEX[_member], ())
        VOWEL_CONFUSION_IDX[JUNG_INDEX[_member]] += _others
CONFUSABLE_JUNG_INDICES = frozenset(VOWEL_CONFUSION_IDX)

del _group, _member, _others
